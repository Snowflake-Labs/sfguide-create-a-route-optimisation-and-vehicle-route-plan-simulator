CREATE SCHEMA IF NOT EXISTS FLEET_INTELLIGENCE.RETAIL_CATCHMENT
    COMMENT = '{"origin":"sf_sit-is-fleet","name":"oss-retail-catchment","version":{"major":1,"minor":0},"attributes":{"is_quickstart":1,"source":"sql"}}';

CREATE TABLE IF NOT EXISTS FLEET_INTELLIGENCE.RETAIL_CATCHMENT.CONFIG (
    VEHICLE_TYPE VARCHAR NOT NULL, REGION VARCHAR NOT NULL
) COMMENT = '{"origin":"sf_sit-is-fleet","name":"oss-retail-catchment","version":{"major":1,"minor":0},"attributes":{"is_quickstart":1,"source":"sql"}}';
MERGE INTO FLEET_INTELLIGENCE.RETAIL_CATCHMENT.CONFIG tgt
USING (SELECT 'ebike' AS VEHICLE_TYPE, 'SanFrancisco' AS REGION) src
ON TRUE
WHEN NOT MATCHED THEN INSERT (VEHICLE_TYPE, REGION) VALUES (src.VEHICLE_TYPE, src.REGION);

CREATE TABLE IF NOT EXISTS FLEET_INTELLIGENCE.RETAIL_CATCHMENT.REGION_CONFIG (
    REGION VARCHAR NOT NULL, REGION_NAME VARCHAR, BBOX_MIN_LON FLOAT, BBOX_MIN_LAT FLOAT,
    BBOX_MAX_LON FLOAT, BBOX_MAX_LAT FLOAT, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = '{"origin":"sf_sit-is-fleet","name":"oss-retail-catchment","version":{"major":1,"minor":0},"attributes":{"is_quickstart":1,"source":"sql"}}';
MERGE INTO FLEET_INTELLIGENCE.RETAIL_CATCHMENT.REGION_CONFIG tgt
USING (SELECT 'SanFrancisco' AS REGION, 'San Francisco Bay Area' AS REGION_NAME,
       -123.0 AS BBOX_MIN_LON, 36.8 AS BBOX_MIN_LAT, -121.5 AS BBOX_MAX_LON, 38.5 AS BBOX_MAX_LAT) src
ON tgt.REGION = src.REGION
WHEN NOT MATCHED THEN INSERT VALUES (src.REGION, src.REGION_NAME, src.BBOX_MIN_LON, src.BBOX_MIN_LAT, src.BBOX_MAX_LON, src.BBOX_MAX_LAT, CURRENT_TIMESTAMP());

CREATE OR REPLACE TABLE FLEET_INTELLIGENCE.RETAIL_CATCHMENT.RETAIL_POIS (
    REGION VARCHAR NOT NULL, POI_ID VARCHAR, POI_NAME VARCHAR, BASIC_CATEGORY VARCHAR,
    LONGITUDE FLOAT, LATITUDE FLOAT, GEOMETRY GEOGRAPHY, ADDRESS VARCHAR, CITY VARCHAR, STATE VARCHAR, POSTCODE VARCHAR
) COMMENT = '{"origin":"sf_sit-is-fleet","name":"oss-retail-catchment","version":{"major":1,"minor":0},"attributes":{"is_quickstart":1,"source":"sql"}}';

INSERT INTO FLEET_INTELLIGENCE.RETAIL_CATCHMENT.RETAIL_POIS
SELECT 'SanFrancisco' AS REGION, ID AS POI_ID, NAMES:primary::VARCHAR AS POI_NAME, BASIC_CATEGORY,
    ST_X(GEOMETRY) AS LONGITUDE, ST_Y(GEOMETRY) AS LATITUDE, GEOMETRY,
    COALESCE(ADDRESSES[0]:freeform::VARCHAR, '') AS ADDRESS,
    ADDRESSES[0]:locality::VARCHAR AS CITY, ADDRESSES[0]:region::VARCHAR AS STATE, ADDRESSES[0]:postcode::VARCHAR AS POSTCODE
FROM OVERTURE_MAPS__PLACES.CARTO.PLACE
WHERE BASIC_CATEGORY IN ('coffee_shop','fast_food_restaurant','restaurant','casual_eatery','grocery_store','convenience_store','gas_station','pharmacy','clothing_store','electronics_store','specialty_store','gym','beauty_salon','hair_salon','bakery','bar','supermarket')
AND GEOMETRY IS NOT NULL AND ADDRESSES[0]:region IS NOT NULL
AND ST_X(GEOMETRY) BETWEEN -123.0 AND -121.5
AND ST_Y(GEOMETRY) BETWEEN 36.8 AND 38.5;

CREATE OR REPLACE TABLE FLEET_INTELLIGENCE.RETAIL_CATCHMENT.CITIES_BY_STATE (
    REGION VARCHAR NOT NULL, STATE VARCHAR, CITY VARCHAR, POI_COUNT INT
) COMMENT = '{"origin":"sf_sit-is-fleet","name":"oss-retail-catchment","version":{"major":1,"minor":0},"attributes":{"is_quickstart":1,"source":"sql"}}';
INSERT INTO FLEET_INTELLIGENCE.RETAIL_CATCHMENT.CITIES_BY_STATE
SELECT 'SanFrancisco', STATE, CITY, COUNT(*) FROM FLEET_INTELLIGENCE.RETAIL_CATCHMENT.RETAIL_POIS
WHERE REGION = 'SanFrancisco' GROUP BY STATE, CITY;

