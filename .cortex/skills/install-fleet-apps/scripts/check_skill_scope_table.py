#!/usr/bin/env python3
"""Keep the install-fleet-apps SKILL.md scope lists equal to what is installed.

The hand-written scope table once listed Backload Matching and SV_BACKLOAD_MATCHING
as EXCLUDED while the installer shipped both: a fresh-clone install showed Backload
Matching, Backload Proposals and Triangle Proposals in the SA app view picker. The
lists between the `scope:begin` / `scope:end` markers are therefore GENERATED from
the sources the app and installer read:

  UI views        fleet_sa_app/app/app-views.json + ui/src/lib/packs/*/pack-views.json
                  (labels rendered with the seed's default nouns)
  semantic views  every `CREATE ... SEMANTIC VIEW ... SV_*` in the installer's SQL

Usage: check_skill_scope_table.py           fail on drift
       check_skill_scope_table.py --write   regenerate the block in place
"""
import json
import pathlib
import re
import sys

SKILL_DIR = pathlib.Path(__file__).resolve().parents[1]
SKILL = SKILL_DIR / "SKILL.md"
APP = SKILL_DIR / "fleet_sa_app"
BEGIN, END = "<!-- scope:begin (generated by scripts/check_skill_scope_table.py --write) -->", "<!-- scope:end -->"
# The seed preset's nouns (SanFrancisco/ebike), as the SA app picker renders them.
DEFAULT_LABELS = {"entity": "Vehicle", "journey": "Trip", "operator": "Driver"}
SV_SOURCES = ["fleet_sa_app/app/*.sql", "scripts/*.sql", "scripts/overture_semantic/*.sql"]
SV_RE = re.compile(r"SEMANTIC\s+VIEW\s+(?:IF\s+NOT\s+EXISTS\s+)?[\w$.\"]*?\b(SV_[A-Z0-9_]+)", re.I)


def _render(label: str) -> str:
    return re.sub(r"\{\{\s*labels\.(\w+)\s*\}\}", lambda m: DEFAULT_LABELS.get(m.group(1), m.group(1)), label)


def view_labels() -> list[str]:
    files = [APP / "app" / "app-views.json", *sorted((APP / "ui/src/lib/packs").glob("*/pack-views.json"))]
    out: list[str] = []
    for f in files:
        data = json.loads(f.read_text())
        for v in (data.values() if isinstance(data, dict) else data):
            if isinstance(v, dict) and v.get("label"):
                out.append(_render(v["label"]))
    return out


def semantic_views() -> list[str]:
    found: set[str] = set()
    for pattern in SV_SOURCES:
        for f in SKILL_DIR.glob(pattern):
            for line in f.read_text(errors="replace").splitlines():
                if line.lstrip().startswith("--"):
                    continue
                found.update(m.upper() for m in SV_RE.findall(line))
    return sorted(found)


def block() -> str:
    views = view_labels()
    return "\n".join([
        BEGIN,
        f"- **UI views ({len(views)}):** " + ", ".join(views) + ".",
        "- **Semantic views:** " + ", ".join(f"`{s}`" for s in semantic_views()) + ".",
        END,
    ])


def main() -> int:
    text = SKILL.read_text()
    if BEGIN not in text or END not in text:
        print(f"FAIL {SKILL.relative_to(SKILL_DIR.parents[2])}: scope markers missing")
        return 1
    head, rest = text.split(BEGIN, 1)
    current, tail = rest.split(END, 1)
    want = block()
    if "--write" in sys.argv:
        SKILL.write_text(head + want + tail)
        print("wrote scope block")
        return 0
    if BEGIN + current + END != want:
        have, need = set(re.findall(r"[^,:*]+", current)), set(re.findall(r"[^,:*]+", want))
        missing = sorted(s.strip(" .`\n") for s in need - have if s.strip(" .`\n"))
        print("FAIL SKILL.md scope block is stale vs app-views/pack-views/semantic-view SQL; "
              "run scripts/check_skill_scope_table.py --write")
        for m in missing[:20]:
            print(f"  missing or changed: {m}")
        return 1
    # Prose outside the block must not re-grow an EXCLUDED list naming installed items
    # (the original defect was an EXCLUDED table column).
    installed = view_labels() + semantic_views()
    for line in (head + tail).splitlines():
        if re.search(r"\bEXCLUDED\b", line):
            hit = [n for n in installed if n in line]
            if hit:
                print(f"FAIL SKILL.md calls installed item(s) excluded: {', '.join(hit)}")
                return 1
    print("ok  SKILL.md scope block matches the installed views and semantic views")
    return 0


if __name__ == "__main__":
    sys.exit(main())
