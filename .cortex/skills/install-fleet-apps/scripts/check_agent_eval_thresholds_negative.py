#!/usr/bin/env python3
"""Negative tests for check_agent_eval_thresholds.py (live gate).

A fresh install has never run an agent evaluation, so no healthy account can be
recorded. The cassette is SYNTHETIC instead: a responder answers the gate's two
queries (newest run per agent; that run's per-record scores) and this driver
records it once into live_cassettes/agent_eval_thresholds.json (regenerated by
running with --record). Scores reproduce the documented shape: every metric's
MEAN clears its threshold while single records sit below it - the per-record
check that "reported 13 breaches on an agent that passes every metric" must stay
gone, so the healthy baseline is also the over-tightening guard.
"""
import json
import os
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from negtest import Harness  # noqa: E402

S = ".cortex/skills/install-fleet-apps/scripts"
CASSETTE = f"{S}/live_cassettes/agent_eval_thresholds.json"
STATUS = [{"status": "Statement executed successfully."}]

RESPONDER = r'''#!/usr/bin/env python3
import json, sys
q = sys.argv[sys.argv.index("-q") + 1]
st = [{"status": "Statement executed successfully."}]
if "GET_AI_OBSERVABILITY_LOGS" in q:
    print(json.dumps([st, [{"RUN_NAME": "baseline-synthetic"}]]))
elif "GET_AI_EVALUATION_DATA" in q:
    rows = []
    for metric, scores in {"answer_correctness": [0.9, 0.3, 0.8],
                           "logical_consistency": [0.7, 0.6],
                           "tool_selection_accuracy": [0.2, 0.9, 0.9],
                           "tool_execution_accuracy": [0.5, 0.6]}.items():
        rows += [{"METRIC_NAME": metric, "EVAL_AGG_SCORE": s} for s in scores]
    print(json.dumps([st, rows]))
else:
    sys.stderr.write("unexpected query\n"); sys.exit(1)
'''


def record() -> None:
    from fake_snow import fake_snow_bin
    d = tempfile.mkdtemp()
    real = pathlib.Path(d) / "responder.py"
    real.write_text(RESPONDER.replace("#!/usr/bin/env python3", f"#!{sys.executable}", 1))
    real.chmod(0o755)
    cas = HERE.parents[3] / CASSETTE
    cas.unlink(missing_ok=True)
    env = dict(os.environ, FAKE_SNOW_MODE="record", FAKE_SNOW_CASSETTE=str(cas),
               FAKE_SNOW_REAL=str(real), PATH=f"{fake_snow_bin()}{os.pathsep}{os.environ['PATH']}")
    p = subprocess.run([sys.executable, str(HERE / "check_agent_eval_thresholds.py"), "-c", "x"],
                       env=env, capture_output=True, text=True)
    print(p.stdout + p.stderr)
    print(f"recorded {cas} (rc={p.returncode})")


if "--record" in sys.argv:
    record()
    sys.exit(0)

h = Harness("check_agent_eval_thresholds.py", args=["-c", "replayed"], cassette=CASSETTE)
EVAL = "GET_AI_EVALUATION_DATA"
h.account("one metric's mean drops below its threshold",
          [{"match": EVAL, "replace": [['"EVAL_AGG_SCORE": 0.7', '"EVAL_AGG_SCORE": 0.1'],
                                       ['"EVAL_AGG_SCORE": 0.6', '"EVAL_AGG_SCORE": 0.1']]}],
          expect="logical_consistency: mean 0.100")
h.account("an agent was never evaluated (fresh install)",
          [{"match": "GET_AI_OBSERVABILITY_LOGS", "stdout": json.dumps([STATUS, []])}],
          expect="NOT_RUN")
h.account("the run carries no gateable metric",
          [{"match": EVAL, "stdout": json.dumps([STATUS, [{"METRIC_NAME": "latency", "EVAL_AGG_SCORE": 1}]])}],
          expect="no threshold-able metrics")
h.account("the evaluation query errors (an error is not a pass)",
          [{"match": EVAL, "rc": 1, "stdout": "", "stderr": "002003: does not exist"}],
          expect="no threshold-able metrics")
sys.exit(h.finish())
